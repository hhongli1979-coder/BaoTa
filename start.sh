#!/bin/bash
# 宝塔面板启动脚本

echo "=========================================="
echo "      宝塔面板 Docker 容器启动中...      "
echo "=========================================="
echo ""

# 启动宝塔面板服务
echo "正在启动宝塔面板服务..."
/etc/init.d/bt start

echo ""
echo "=========================================="
echo "      宝塔面板启动成功！                "
echo "=========================================="
echo ""

# 显示宝塔面板默认信息（账号密码等）
echo "默认登录信息："
echo "----------------------------------------"
bt default
echo "----------------------------------------"
echo ""

echo "访问提示："
echo "1. 请使用上方显示的面板地址和端口访问"
echo "2. 首次登录需要使用上方的用户名和密码"
echo "3. 如需修改密码，请使用命令: bt 14"
echo "4. 如需修改端口，请使用命令: bt 8"
echo ""

echo "常用命令："
echo "  bt default    - 查看面板默认信息"
echo "  bt restart    - 重启面板服务"
echo "  bt stop       - 停止面板服务"
echo "  bt start      - 启动面板服务"
echo "  bt 14         - 修改面板密码"
echo "  bt 8          - 修改面板端口"
echo ""

echo "容器保持运行中..."
echo "=========================================="

# 保持容器运行
tail -f /dev/null
